export function translateAdminValue(
  t: AdminTranslate,
  group: keyof typeof valueTranslationKeys,
  value: string,
): string {
  const keys = valueTranslationKeys[group] as Record<
    string,
    AdminTranslationKey | undefined
  >;
  const key = keys[value];
  return key ? t(key) : value;
}

/** Every audited action with its label, for filtering the audit log. */
export function auditActionOptions(
  t: AdminTranslate,
): { value: string; label: string }[] {
  return Object.entries(valueTranslationKeys.auditAction).map(
    ([value, key]) => ({ value, label: t(key) }),
  );
}
